CREATE TABLE tb_category (
                             id_category  NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                             name         VARCHAR2(80) NOT NULL,
                             CONSTRAINT uq_category_name UNIQUE (name)
);

CREATE TABLE tb_product (
                            id_product   NUMBER GENERATED BY DEFAULT AS IDENTITY (START WITH 100) PRIMARY KEY,
                            id_category  NUMBER        NOT NULL,
                            name         VARCHAR2(150) NOT NULL,
                            brand        VARCHAR2(60)  NOT NULL,
                            description  VARCHAR2(500),
                            price        NUMBER(10,2)  NOT NULL,
                            unit         VARCHAR2(20)  NOT NULL,
                            attributes   VARCHAR2(4000),
                            active       CHAR(1)       DEFAULT 'Y' NOT NULL,
                            CONSTRAINT fk_product_category FOREIGN KEY (id_category) REFERENCES tb_category (id_category),
                            CONSTRAINT ck_product_price    CHECK (price >= 0),
                            CONSTRAINT ck_product_active   CHECK (active IN ('Y', 'N')),
                            CONSTRAINT ck_product_attrs    CHECK (attributes IS JSON)
);

CREATE INDEX ix_product_category ON tb_product (id_category);

CREATE TABLE tb_stock (
                          id_product   NUMBER       PRIMARY KEY,
                          quantity     NUMBER(8)    DEFAULT 0 NOT NULL,
                          aisle        VARCHAR2(10) NOT NULL,
                          shelf        VARCHAR2(10) NOT NULL,
                          updated_at   TIMESTAMP    DEFAULT SYSTIMESTAMP NOT NULL,
                          CONSTRAINT fk_stock_product FOREIGN KEY (id_product) REFERENCES tb_product (id_product),
                          CONSTRAINT ck_stock_quantity CHECK (quantity >= 0)
);

CREATE TABLE tb_complement (
                               id_product     NUMBER        NOT NULL,
                               id_complement  NUMBER        NOT NULL,
                               reason         VARCHAR2(250) NOT NULL,
                               CONSTRAINT pk_complement PRIMARY KEY (id_product, id_complement),
                               CONSTRAINT fk_complement_product    FOREIGN KEY (id_product)    REFERENCES tb_product (id_product),
                               CONSTRAINT fk_complement_complement FOREIGN KEY (id_complement) REFERENCES tb_product (id_product),
                               CONSTRAINT ck_complement_distinct   CHECK (id_product <> id_complement)
);

